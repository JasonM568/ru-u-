import type { CcMode } from "./ccc";

export type CardId = "L0" | "L1" | "L2" | "XS" | "L3" | "L4";

export const CARD_LABEL: Record<CardId, string> = {
  L0: "L0 交棒卡",
  L1: "L1 交棒卡",
  L2: "L2 交棒卡",
  XS: "交集卡",
  L3: "L3 交棒卡",
  L4: "L4 交棒卡",
};

export type PromptContext = {
  /** L0 第 ④ 項的產業鏈名稱 */
  chain: string;
  /** "ai" = 教材群組（指令原文照用）；"custom" = 自訂產業鏈（介面在 AI 專用段落加提示，字串不變） */
  chainKind: "ai" | "custom";
  /** 已格式化的個股清單，每行「子段：代號 名稱、代號 名稱」 */
  roster: string;
  /** 掃描檔數 */
  count: number;
  /** 目前啟用的子段名稱 */
  subNames: string[];
  /** L2 的產業註記 */
  l2note: string;
  /** 參考 WACC，字串以保留使用者輸入 */
  wacc: string;
  /** L3 標的，如「1519 華城」 */
  target: string;
  cards: Record<CardId, string>;
  ccMode: CcMode;
};

/** 交棒卡未填時，在指令裡留下明顯的佔位符（UI 會標紅）。 */
function card(ctx: PromptContext, id: CardId): string {
  const v = (ctx.cards[id] ?? "").trim();
  return v || `〔尚未貼入 ${CARD_LABEL[id]}〕`;
}

const slash = (ctx: PromptContext) => ctx.subNames.join("／");
const sltLine = (ctx: PromptContext) => ctx.subNames.map((n) => `${n} __`).join(" ");

