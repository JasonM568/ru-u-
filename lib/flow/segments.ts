/**
 * AI 供應鏈分段資料。
 *
 * 資料來源分兩種，**不可混為一談**：
 *  - `added` 未設定 = 教材原表（《AI 供應鏈投資判斷一覽表(Elite)》74 檔），段位先驗是顧老師的判斷。
 *  - `added: true` = 非教材原表，由 Claude 依訓練資料補充（知識截止 2026-05），
 *    代號、公司名與所屬子段**都需要自行查證**，段位一律「未定」，不代填老師的先驗判斷。
 *
 * 段位先驗只是起點，不是結論。實際歸屬要在 L2 用當期財報
 * （毛利率趨勢、ROIC、交期、擴產宣告）驗證後才算數。
 */

export type Prior = "瓶頸" | "通過" | "被替代" | "循環" | "形成期" | "未定";

export type Stock = {
  code: string;
  name: string;
  prior: Prior;
  /** true = 非教材原表，Claude 補充，需查證 */
  added?: boolean;
};

/** 一覽表「分組門檻」分頁的五個門檻，順序固定。 */
export type Thresholds = {
  revYoY: number;
  opYoY: number;
  opMargin: number;
  debtRatio: number;
  fcfYears: number;
};

export type Segment = {
  /** 教材分類名（唯一鍵） */
  key: string;
  /** 顯示用短名 */
  short: string;
  th: Thresholds;
  stocks: Stock[];
};

export type Group = {
  id: string;
  name: string;
  /** L0 指令第 ④ 項要填的產業鏈名稱 */
  chain: string;
  /** 分組出處：教材原例 or 預設分組 */
  src: string;
  subs: string[];
  /** L2 指令的產業註記 */
  l2note: string;
};

const th = (
  revYoY: number,
  opYoY: number,
  opMargin: number,
  debtRatio: number,
  fcfYears: number,
): Thresholds => ({ revYoY, opYoY, opMargin, debtRatio, fcfYears });

/** 教材原表個股 */
const s = (code: string, name: string, prior: Prior): Stock => ({ code, name, prior });
/** Claude 補充個股：段位一律「未定」 */
const add = (code: string, name: string): Stock => ({
  code,
  name,
  prior: "未定",
  added: true,
});

