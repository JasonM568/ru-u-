/** 找出某代號出現在哪些分類（台積電、群聯、臻鼎-KY 會橫跨兩段）。 */
export function findByCode(code: string): { segment: Segment; stock: Stock; group?: Group }[] {
  const out: { segment: Segment; stock: Stock; group?: Group }[] = [];
  for (const seg of Object.values(SEGMENTS)) {
    const hit = seg.stocks.find((x) => x.code === code);
    if (hit) {
      out.push({
        segment: seg,
        stock: hit,
        group: GROUPS.find((g) => g.subs.includes(seg.key)),
      });
    }
  }
  return out;
}

